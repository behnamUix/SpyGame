    fun configRole(useSecureRandom: Boolean) {
        viewModelScope.launch {
            setLog("spyCount = $spyCount, agentCount = $agentCount")

            val list = mutableListOf<Player>()
            for (i in 1..agentCount) {
                list.add(Player(i, "تو الان یه مامور هستی"))
            }
            for (i in 1..spyCount) {
                list.add(Player(i + agentCount, "تو یه جاسوسی"))
            }

            val shuffled = shuffledList(useSecureRandom, list)
            _playerList.emit(shuffled)
            shuffled.forEach {
                setLog(it.role)
            }
        }
    }

    fun incTime() {
        setTime((_baseTimeInMinutes.value + 2).coerceAtMost(15))
    }

    fun decTime() {
        setTime((_baseTimeInMinutes.value - 2).coerceAtLeast(2))
    }

    fun setTime(minutes: Int) {
        val clampedMinutes = minutes.coerceIn(2, 15) // محدود کردن بین 2 تا 15 دقیقه
        _baseTimeInMinutes.value = clampedMinutes
    }


